'use strict';
const assert=require('node:assert/strict'),core=require('../lib/report-obligations.js');
const employee={id:'worker',name:'Worker',status:'Aktivan',startDate:'2026-11-01',weeklyHours:38.5,leaderId:'leader'};
const p={employees:[employee],employeeReports:[],employeeWorkLogs:[],employeeAbsences:[],unrelated:{keep:'exact'}};
const now=new Date('2026-11-27T15:01:00Z');
assert.equal(core.ensure(p,now),4,'Three daily obligations and one weekly, independent of login');
assert.equal(core.ensure(p,now),0,'Retry cannot duplicate obligations');
assert.deepEqual(p.unrelated,{keep:'exact'});
assert.equal(core.pending(p,employee,now).length,4);
assert.equal(core.pending(p,employee,now).filter(t=>t.overdue).length,4);
assert.equal(core.pending(p,employee,new Date('2026-11-27T14:59:00Z')).filter(t=>t.overdue).length,2,'Friday deadline is 16:00 Vienna');
assert.equal(core.endTime({...employee,weeklyHours:20},'2026-11-26'),'13:00');
assert.equal(core.local(new Date('2027-03-29T15:30:00Z')).time,'17:30','DST uses Vienna');
const daily=p.employeeReports.find(r=>r.date==='2026-11-25'&&r.isFinalDailyReport);
daily.note='An automatic summary is not a submission';daily.positive='x';daily.negative='x';daily.help='x';
assert.equal(core.complete(daily),false);
daily.isAutomaticRollup=false;
assert.equal(core.complete(daily),true);
assert(!core.pending(p,employee,now).some(t=>t.id===daily.id));
const historic={id:'old',employeeId:employee.id,date:'2026-11-24',isFinalDailyReport:true,isAutomaticRollup:true};
assert.equal(core.policy(p,employee,historic,now),null,'Legacy debt cannot lock employees');
p.employeeAbsences.push({employeeId:'worker',status:'Odobreno',startDate:'2026-11-27',endDate:'2026-11-27'});
const weekly=p.employeeReports.find(r=>r.isWeeklyQuestionnaire);
assert.equal(core.policy(p,employee,weekly,now).dueDate,'2026-11-30','Leave on deadline postpones until next working day');
const client={id:'clients',employeeId:'worker',date:'2026-11-30',dueDate:'2026-12-01',periodStart:'2026-11-23',periodEnd:'2026-11-29',isClientWeeklyReport:true,clients:[{clientId:'a'}]};
assert.equal(core.policy(p,{...employee,isLeader:true},client,now),null,'Leaders do not owe client reviews');
p.employeeAbsences=[{employeeId:'worker',status:'Odobreno',startDate:'2026-11-23',endDate:'2026-11-29'}];
assert.equal(core.policy(p,employee,weekly,now),null,'Full-week leave exempts weekly report');
p.employeeWorkLogs.push({id:'actual-work',employeeId:'worker',date:'2026-11-26',minutes:15});
assert(core.policy(p,employee,weekly,now),'Actual work during leave requires a report');
assert.equal(core.policy(p,employee,p.employeeReports.find(r=>r.date==='2026-11-26'&&r.isFinalDailyReport),now).needsTime,false);
console.log('PASS report obligations: deterministic durable backlog, rollout boundary, manual completion, Vienna/DST deadlines, part time, absences, leader exemptions, unrelated data preservation');
